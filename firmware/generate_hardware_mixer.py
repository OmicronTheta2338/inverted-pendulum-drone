#!/usr/bin/env python3
"""Generate the level, low-output allocation for this rectangular eight-motor frame."""
import json
from pathlib import Path
import re

root = Path(__file__).resolve().parent
layout = json.loads((root/'hardware-layout.json').read_text())
motors = layout['motors']
k = layout['torque_per_thrust_m_assumed']
xf = motors[0]['r_frd_m'][0]
xr = -motors[4]['r_frd_m'][0]
lf = motors[1]['r_frd_m'][0]
lr = -motors[5]['r_frd_m'][0]
assert xf > 0 and xr > 0 and lf > 0 and lr > 0 and k > 0
assert all(m['r_frd_m'][2] == 0 for m in motors if m['number']%2 == 0)
# Equal front/rear lateral forces give yaw = (lf-lr)*command.
# A zero-net-lift diagonal correction supplies the opposing propeller yaw torque.
lateral_yaw_trim = -(lf-lr)/(4*k)
lift_yaw_weight = k / ((lf+lr)/2)
text = '''-- Generated by generate_hardware_mixer.py; edit hardware-layout.json, then regenerate.
-- Body FRD; odd outputs lift, even outputs push outwards left/right.
-- Shaft-view M1/M2/M5/M6 CCW, others CW. See HARDWARE-MIXER.md.
-- Collective front/rear weights account for measured forward CoM offset.
-- Lift-only roll/pitch; yaw uses both lift reaction torque and lateral thrust.
-- Lift differential on the right-demand column cancels lateral-thrust offset yaw.
-- This is not a general inverse allocator: saturation/tilt/mixed-command coupling remains.
-- add_motor(index, roll, pitch, yaw, up, forward, right, reversible, test_order)
'''
for m in motors:
    i = m['number']; x,y,z = m['r_frd_m']
    spin = 1 if m['rotation_viewed_from_shaft_end']=='CCW' else -1
    if i%2:
        vals = [1 if y<0 else -1, 1 if x>0 else -1,
                spin*lift_yaw_weight, 1 if x>0 else xf/xr, 0,
                spin*lateral_yaw_trim]
    else:
        right = m['thrust_unit_frd'][1]
        vals = [0,0,(1 if x>0 else -1)*right,0,0,right]
    row = ', '.join(f'{v:.12f}' for v in vals)
    text += f'Motors_6DoF:add_motor({i-1}, {row}, false, {i}) -- M{i} {m["position"]}\n'
text += '''
assert(Motors_6DoF:init(8), 'base drone: eight-motor mixer init failed')
motors:set_frame_string("BaseDrone Hardware 6DoF")

function update()
    attitude_control:set_forward_enable(false)
    attitude_control:set_lateral_enable(true)
    return update, 100
end
return update()
'''
(root/'scripts/base_drone.lua').write_text(text)
crc=0
for byte in text.encode():
    crc ^= byte
    for _ in range(8):
        crc = (crc>>1) ^ (0xedb88320 if crc&1 else 0)
crc &= 0x7fffff
params=root/'base-drone.parm'
params.write_text(re.sub(r'(SCR_(?:LD|RUN)_CHECKSUM) \d+',lambda m:m[1]+' '+str(crc),params.read_text()))
print('Generated mixer, checksum',crc)
